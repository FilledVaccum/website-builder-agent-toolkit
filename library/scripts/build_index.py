#!/usr/bin/env python3
"""Build library/INDEX.md from the frontmatter of library/items/*.md (stdlib only)."""
import re
import sys
from pathlib import Path

LIB = Path(__file__).resolve().parent.parent
ITEMS = LIB / "items"
# Metadata fields; every other frontmatter key is a tag dimension (new ones are picked up automatically).
META = {"slug", "name", "url", "local", "summary", "stars", "last_push", "added", "related"}
# Preferred order of known dimensions in INDEX.md; unknown/new dimensions are appended alphabetically.
ORDER = ["type", "stage", "task", "content", "content-format", "agent", "software", "channel",
         "cost", "license", "commercial-use", "requires", "level", "source", "maturity", "verified"]
OPEN_ENDED = {"software"}  # values not required to be listed in TAXONOMY.md


def parse(path: Path) -> dict:
    text = path.read_text()
    m = re.match(r"---\n(.*?)\n---\n", text, re.S)
    if not m:
        sys.exit(f"{path.name}: missing frontmatter")
    card = {"slug": path.stem}
    for line in m.group(1).splitlines():
        if not line.strip() or ":" not in line:
            continue
        key, val = line.split(":", 1)
        val = re.sub(r"\s+#.*$", "", val).strip()
        if val.startswith("[") and val.endswith("]"):
            card[key.strip()] = [v.strip() for v in val[1:-1].split(",") if v.strip()]
        else:
            card[key.strip()] = val
    for f in ("type", "stage", "task", "agent", "software", "channel", "related"):
        v = card.get(f, [])
        card[f] = v if isinstance(v, list) else [v] if v and v != "-" else []
    return card


def dimensions(cards):
    found = {k for c in cards for k in c if k not in META}
    return [d for d in ORDER if d in found] + sorted(found - set(ORDER))


def as_list(v):
    return v if isinstance(v, list) else [v] if v else []


def check_tags(cards, dims):
    """Warn on tag values not yet listed in TAXONOMY.md, so the taxonomy is kept in sync as it grows."""
    allowed = set(re.findall(r"`([a-z0-9][a-z0-9.\-]*)`", (LIB / "TAXONOMY.md").read_text()))
    bad = 0
    for c in cards:
        for dim in dims:
            if dim in OPEN_ENDED:
                continue
            for v in as_list(c.get(dim)):
                if v not in allowed:
                    print(f"add to TAXONOMY.md: {dim} = {v}  (used by {c['slug']})", file=sys.stderr)
                    bad += 1
    return bad


def link(c):
    return f"[{c.get('name', c['slug'])}](items/{c['slug']}.md)"


def main():
    cards = sorted((parse(p) for p in ITEMS.glob("*.md")),
                   key=lambda c: (as_list(c["stage"]) or ["99"])[0] + c.get("name", ""))
    dims = dimensions(cards)
    check_tags(cards, dims)
    out = ["# Library index",
           "",
           "*Generated by `library/scripts/build_index.py` from `items/*.md`. Do not edit by hand.*",
           "",
           f"**{len(cards)} items.** Tag meanings: [TAXONOMY.md](TAXONOMY.md).",
           "",
           "## All items",
           "",
           "| Item | Type | Stage | Task | Platform (agent / software / channel) | Cost | Commercial use | Verified |",
           "|---|---|---|---|---|---|---|---|"]
    for c in cards:
        plat = " / ".join(", ".join(c[f]) or "—" for f in ("agent", "software", "channel"))
        out.append(f"| {link(c)} | {', '.join(c['type'])} | {', '.join(c['stage'])} | "
                   f"{', '.join(c['task'])} | {plat} | {c.get('cost', '—')} | "
                   f"{c.get('commercial-use', '—')} | {c.get('verified', '—')} |")
    out += ["", "## By tag", ""]
    for dim in dims:
        groups = {}
        for c in cards:
            for v in as_list(c.get(dim)):
                groups.setdefault(v, []).append(c)
        if not groups:
            continue
        out += [f"### By {dim}", ""]
        for v in sorted(groups):
            out.append(f"- **{v}**: " + ", ".join(link(c) for c in groups[v]))
        out.append("")
    (LIB / "INDEX.md").write_text("\n".join(out).rstrip() + "\n")
    print(f"INDEX.md: {len(cards)} items")


if __name__ == "__main__":
    main()
